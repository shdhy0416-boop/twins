const STICKER_LOOKUP: Record<string, Sticker3DItem> = STICKERS_3D_COLLECTION.reduce(
  (acc, item) => {
    acc[item.id] = item;
    return acc;
  },
  {} as Record<string, Sticker3DItem>
);

export function getStickerById(stickerId: string): Sticker3DItem | undefined {
  return STICKER_LOOKUP[stickerId];
}

export function getStickerImageById(stickerId: string): string {
  return STICKER_LOOKUP[stickerId]?.image || '/stickers/sticker_cat.jpg';
}
